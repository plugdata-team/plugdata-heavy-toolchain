#!/bin/sh
GENERATOR=pd
HV_GENERATOR=pdext
MODE=build
. "$(dirname -- "$0")/common.sh"
COPY_TO=
OPTIONS_HELP='  --copy-to DIR    Also copy the built external into DIR, e.g. the plugdata Externals folder'
parse_option() {
    if [ "$1" = --copy-to ]; then
        [ "$#" -ge 2 ] || fail "Missing value for $1"
        COPY_TO=$2
        CONSUMED=2
    fi
}
parse_args "$@"
if [ "$MODE" = build ]; then
    run_command cd -- "$OUTPUT"
    if [ -n "$EXE" ]; then
        make_project PDINCLUDEDIR=pdext suppress-wunused=1 system=Windows
    elif [ "$(uname -s)" = Darwin ]; then
        # xPack reports aarch64 in its target triple; Apple's -arch uses arm64.
        make_project PDINCLUDEDIR=pdext suppress-wunused=1 "arch=$(uname -m)"
    else
        make_project PDINCLUDEDIR=pdext suppress-wunused=1
    fi
    # Keep only the external; the sources and Makefiles are regenerated by every export.
    run_command rm -rf -- c pdext Makefile Makefile.pdlibbuilder
    if [ -n "$COPY_TO" ]; then
        run_command mkdir -p -- "$COPY_TO"
        run_command cp -- "$NAME"~.* "$COPY_TO/"
    fi
fi
