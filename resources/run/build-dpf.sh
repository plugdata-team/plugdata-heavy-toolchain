#!/bin/sh
GENERATOR=dpf
HV_GENERATOR=dpf
MODE=build
. "$(dirname -- "$0")/common.sh"
DEFAULT_META="$RUN_DIR/dpf-defaults.json"
parse_args "$@"
copy_library DPF dpf
copy_library dpf-widgets dpf-widgets
copy_library pdvg pdvg
run_command rm -rf -- "$OUTPUT/c"
if [ "$MODE" = build ]; then
    run_command cd -- "$OUTPUT"
    make_project plugin lv2_ttl_generator
    # The upstream helper uses Bash syntax and unquoted absolute paths.
    # Generate LV2 metadata directly with the built DPF utility instead.
    for bundle in "$OUTPUT"/bin/*.lv2; do
        [ -d "$bundle" ] || continue
        for plugin in "$bundle"/*.so "$bundle"/*.dylib "$bundle"/*.dll; do
            [ -f "$plugin" ] || continue
            (run_command cd -- "$bundle" && run_command "$OUTPUT/dpf/utils/lv2_ttl_generator$EXE" "./${plugin##*/}")
            break
        done
    done
    # Move the plugins to the top of the output folder, replacing those of an earlier export.
    for result in bin/*; do
        [ -e "$result" ] || continue
        run_command rm -rf -- "${result#bin/}"
        run_command mv -- "$result" .
    done
    # Keep only the plugins; the project and libraries are regenerated by every export.
    run_command rm -rf -- bin build plugin dpf dpf-widgets pdvg Makefile README.md
fi
