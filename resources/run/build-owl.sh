#!/bin/sh
GENERATOR=owl
HV_GENERATOR=OWL
MODE=build
. "$(dirname -- "$0")/common.sh"
parse_args "$@"
copy_library OwlProgram OwlProgram
run_command rm -rf -- "$OUTPUT/c"
if [ "$MODE" != source ]; then
    run_command cd -- "$OUTPUT/OwlProgram"
    target=patch
    case $MODE in load|store) target=$MODE;; esac
    # Compiler tools resolve through PATH, avoiding unquoted absolute TOOLROOTs
    # in the upstream Makefiles when the toolchain path contains spaces.
    run_command make -j"$JOBS" "SHELL=$SHELL" TOOLROOT= BUILD=../ "PATCHNAME=$NAME" \
        PATCHCLASS=HeavyPatch "PATCHFILE=HeavyOWL_$NAME.hpp" \
        "PLATFORM=$BOARD" "SLOT=$SLOT" "$target"
    # The build writes into the output folder (BUILD=../). Keep only the firmware;
    # the project, OwlProgram and object files are regenerated by every export.
    run_command cd -- "$OUTPUT"
    run_command mv -- patch.bin "$NAME.bin"
    run_command rm -rf -- OwlProgram Source Test web patch.elf ./*.h ./*.cpp ./*.o ./*.d
fi
